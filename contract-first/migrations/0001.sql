CREATE TABLE IF NOT EXISTS courses (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL, description TEXT, owner_id INTEGER NOT NULL,
    version INTEGER NOT NULL DEFAULT 1, published BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS lessons (id INTEGER PRIMARY KEY, course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE, title TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS enrollments (user_id INTEGER NOT NULL, course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE, PRIMARY KEY (user_id, course_id));
CREATE TABLE IF NOT EXISTS files (id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, course_id INTEGER NOT NULL UNIQUE REFERENCES courses(id) ON DELETE CASCADE, content BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS idempotency (scope TEXT PRIMARY KEY, body TEXT NOT NULL, status INTEGER NOT NULL, result JSONB NOT NULL, expires_at TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS operations (id UUID PRIMARY KEY, user_id INTEGER NOT NULL, status TEXT NOT NULL, format TEXT NOT NULL, result JSONB, error JSONB);
CREATE TABLE IF NOT EXISTS events (id UUID PRIMARY KEY, body JSONB NOT NULL, delivered BOOLEAN NOT NULL DEFAULT false);
